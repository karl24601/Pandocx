// GUI 启动的 Obsidian 在 macOS/Linux 下往往拿不到登录 shell 的 PATH，
// 这里把常见的 pandoc 安装位置补进去。
function buildEnv() {
  const env = Object.assign({}, process.env);
  if (process.platform === 'win32') return env;

  const candidates = [
    '/usr/local/bin',
    '/opt/homebrew/bin',
    '/usr/bin',
    '/bin',
    path.join(os.homedir(), '.local', 'bin'),
    path.join(os.homedir(), '.cabal', 'bin'),
    path.join(os.homedir(), 'bin'),
  ];

  const current = (env.PATH || '').split(path.delimiter).filter(Boolean);
  for (const dir of candidates) {
    if (!current.includes(dir)) current.push(dir);
  }
  env.PATH = current.join(path.delimiter);
  return env;
}

// 把设置里的一串参数拆成数组。
// 逐字符扫描，引号可以出现在 token 中间，例如：
//   --reference-doc="My Template.docx"  ->  ['--reference-doc=My Template.docx']
function splitArgs(str) {
  const out = [];
  let current = '';
  let started = false;   // 区分空 token 与「尚未开始的 token」
  let quote = null;      // 当前所处的引号类型

  for (const ch of str || '') {
    if (quote) {
      if (ch === quote) quote = null;
      else current += ch;
      continue;
    }
    if (ch === '"' || ch === "'") {
      quote = ch;
      started = true;
      continue;
    }
    if (/\s/.test(ch)) {
      if (started) {
        out.push(current);
        current = '';
        started = false;
      }
      continue;
    }
    current += ch;
    started = true;
  }
  if (started) out.push(current);

  return out.filter((a) => a.length > 0);
}

// 去掉 Windows / macOS 不允许出现在文件名里的字符
function sanitizeName(name) {
  return name.replace(/[\\/:*?"<>|]/g, '_').trim();
}

