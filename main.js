class FilenameModal extends Modal {
  constructor(app, sourceName, defaultName, onSubmit) {
    super(app);
    this.sourceName = sourceName;
    this.value = defaultName;
    this.onSubmit = onSubmit;
    this.inputEl = null;
  }

  onOpen() {
    const { contentEl } = this;
    contentEl.addClass('pandocx-modal');

    contentEl.createEl('h3', { text: T.modalTitle });
    contentEl.createEl('p', {
      text: T.sourceLabel(this.sourceName),
      cls: 'setting-item-description',
    });

    new Setting(contentEl)
      .setName(T.outputName)
      .setDesc(T.outputNameDesc)
      .addText((text) => {
        this.inputEl = text.inputEl;
        text.setValue(this.value).onChange((v) => {
          this.value = v;
        });
        text.inputEl.addEventListener('keydown', (evt) => {
          if (evt.key === 'Enter') {
            evt.preventDefault();
            this.submit();
          }
        });
      });

    new Setting(contentEl)
      .addButton((btn) => btn.setButtonText(T.cancel).onClick(() => this.close()))
      .addButton((btn) =>
        btn
          .setButtonText(T.exportBtn)
          .setCta()
          .onClick(() => this.submit())
      );

    // 打开时聚焦并全选，方便直接改名
    window.setTimeout(() => {
      if (this.inputEl) {
        this.inputEl.focus();
        this.inputEl.select();
      }
    }, 0);
  }

  submit() {
    const value = sanitizeName(this.value);
    if (!value) {
      new Notice(T.emptyName);
      return;
    }
    this.close();
    this.onSubmit(value);
  }

  onClose() {
    this.contentEl.empty();
  }
}

