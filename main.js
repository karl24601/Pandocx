module.exports = class PandocxPlugin extends Plugin {
  async onload() {
    this.settings = Object.assign({}, DEFAULT_SETTINGS, await this.loadData());
    this.ensureFilterFile();
    this.addSettingTab(new PandocxSettingTab(this.app, this));

    this.addCommand({
      id: 'export-current-note-to-docx',
      name: T.commandName,
      checkCallback: (checking) => {
        const file = this.app.workspace.getActiveFile();
        if (!file || file.extension !== 'md') return false;
        if (!checking) this.promptAndExport(file);
        return true;
      },
    });

    this.addRibbonIcon('file-output', T.ribbonTooltip, () => {
      const file = this.app.workspace.getActiveFile();
      if (!file || file.extension !== 'md') {
        new Notice(T.openMdFirst);
        return;
      }
      this.promptAndExport(file);
    });

    this.registerEvent(
      this.app.workspace.on('file-menu', (menu, file) => {
        if (!file || file.extension !== 'md') return;
        menu.addItem((item) => {
          item
            .setTitle(T.menuTitle)
            .setIcon('file-output')
            .onClick(() => this.promptAndExport(file));
        });
      })
    );
  }

  async saveSettings() {
    await this.saveData(this.settings);
  }

  getBasePath() {
    const adapter = this.app.vault.adapter;
    if (!(adapter instanceof FileSystemAdapter)) return null;
    return adapter.getBasePath();
  }

  getFilterPath() {
    const base = this.getBasePath();
    if (!base) return null;
    return path.join(base, this.manifest.dir, FILTER_FILENAME);
  }

  // 过滤器不在 release assets 里（BRAT / 社区安装器只取三个文件），
  // 所以缺失时从内嵌源码补写。已存在的文件一律不动。
  ensureFilterFile() {
    const filterPath = this.getFilterPath();
    if (!filterPath) return;
    try {
      if (fs.existsSync(filterPath)) {
        // 只替换我们自己写过的占位版，用户的过滤器不碰
        const current = fs.readFileSync(filterPath, 'utf8');
        if (current.indexOf(PLACEHOLDER_MARKER) !== -1) {
          fs.writeFileSync(filterPath, defaultFilterSource(), 'utf8');
          new Notice(T.filterUpgraded, 10000);
        }
        return;
      }
      fs.writeFileSync(filterPath, defaultFilterSource(), 'utf8');
      new Notice(T.filterCreated, 10000);
    } catch (e) {
      console.error('[pandocx] could not write the default Lua filter', e);
      new Notice(T.filterWriteFailed(e.message), 10000);
    }
  }

  promptAndExport(file) {
    new FilenameModal(this.app, file.name, file.basename, (name) => {
      this.runPandoc(file, name);
    }).open();
  }

  async runPandoc(file, outputName) {
    const basePath = this.getBasePath();
    if (!basePath) {
      new Notice(T.desktopOnly);
      return;
    }

    // 先把编辑器里未落盘的改动写入磁盘
    if (this.settings.saveBeforeExport) {
      try {
        this.app.commands.executeCommandById('editor:save-file');
        await new Promise((r) => window.setTimeout(r, 120));
      } catch (e) {
        // 保存失败不阻断导出
      }
    }

    const inputAbs = path.join(basePath, file.path);
    const sourceDir = path.dirname(inputAbs);

    const filterPath = this.getFilterPath();
    if (!filterPath || !fs.existsSync(filterPath)) {
      new Notice(T.filterMissing(filterPath || ''), 8000);
      return;
    }

    // 输出目录
    let outputDir = sourceDir;
    const configured = (this.settings.outputFolder || '').trim();
    if (configured) {
      outputDir = path.isAbsolute(configured)
        ? configured
        : path.join(basePath, configured);
      try {
        fs.mkdirSync(outputDir, { recursive: true });
      } catch (e) {
        new Notice(T.mkdirFailed(e.message), 8000);
        return;
      }
    }

    const outputAbs = path.join(
      outputDir,
      outputName.replace(/\.docx$/i, '') + '.docx'
    );

    // pandoc <file.md> <extraArgs> --lua-filter=... --resource-path=... -o <out.docx>
    const args = [
      path.basename(inputAbs),
      ...splitArgs(this.settings.extraArgs),
      `--lua-filter=${filterPath}`,
      `--resource-path=${sourceDir}${path.delimiter}${basePath}`,
      '-o',
      outputAbs,
    ];

    const notice = new Notice(T.exporting, 0);

    execFile(
      this.settings.pandocPath || 'pandoc',
      args,
      {
        cwd: sourceDir,
        env: buildEnv(),
        maxBuffer: 32 * 1024 * 1024,
        windowsHide: true,
      },
      (error, stdout, stderr) => {
        notice.hide();

        if (error) {
          if (error.code === 'ENOENT') {
            new Notice(T.pandocMissing, 10000);
          } else {
            const msg = (stderr || error.message || '').trim();
            // Zotero 没开时 pandoc 会吐一大段 Haskell HTTP 异常，
            // 截断后完全没法读，这里换成一句人话。
            if (/\b(23119|24119)\b/.test(msg) || /ConnectionFailure/.test(msg)) {
              new Notice(T.zoteroUnreachable, 12000);
            } else {
              new Notice(T.exportFailed(msg.slice(0, 800)), 12000);
            }
            console.error('[pandocx]', { args, stderr, error });
          }
          return;
        }

        if (stderr && stderr.trim()) {
          console.warn('[pandocx] pandoc warnings:', stderr.trim());
        }

        // 过滤器用 print() 输出诊断，走的是 stdout。pandoc 带 -o 时
        // stdout 是空闲的，所以这里拿得到，必须让用户看见。
        const out = (stdout || '').trim();
        if (out) console.info('[pandocx] filter output:\n' + out);

        new Notice(T.exported(path.basename(outputAbs)), 5000);

        // 过滤器每次运行都会打印版本横幅；没横幅说明它压根没被调用。
        if (!/zotero-live-citations/.test(out)) {
          new Notice(T.filterInactive, 10000);
        }

        // 逐条列出没解析成功的 citekey
        const bad = out
          .split('\n')
          .filter((l) => /not found|not in Zotero|duplicates found|could not fetch/.test(l))
          .map((l) => l.trim());
        if (bad.length) {
          new Notice(T.citationProblems(bad.length, bad.slice(0, 8).join('\n')), 15000);
        }

        if (this.settings.openAfterExport) {
          try {
            const { shell } = require('electron');
            shell.openPath(outputAbs);
          } catch (e) {
            console.warn('[pandocx] could not open the exported file', e);
          }
        }
      }
    );
  }
};

