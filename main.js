// Obsidian 把界面语言存在 localStorage 的 'language' 键里。
function pickLocale() {
  let lang = 'en';
  try {
    lang = window.localStorage.getItem('language') || 'en';
  } catch (e) {
    // 取不到就用英文
  }
  return String(lang).toLowerCase().startsWith('zh') ? LOCALES.zh : LOCALES.en;
}

